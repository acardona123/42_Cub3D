/**
 * @brief initializes the map structure by reading the linked list generated by
 *			in_1_map_format_check,
 *			linking it to the previously generated textures
 * TODO:	function to be done
 * 
 * @param ac 
 * @param av 
 * @param gen 
 * @return EXIT if faillure
 */
void	in_3_map_content_init(t_general *gen, t_lists *lst_init)
{
	t_list	*tmp;
	int		x;
	int		y;

	gen->map = (t_map){lst_init->map_max_x, lst_init->map_max_y,
		lst_init->map_max_x - 1, lst_init->map_max_y - 1, NULL};
	_in_3_alloc_tabmap(gen, lst_init);
	tmp = lst_init->lst_map;
	y = gen->map.height;
	while (tmp)
	{
		x = 0;
		while (tmp->content[x])
		{
			if (!tmp->content[x + 1] && ft_isinset(tmp->content[x], "02WSEN"))
				in_3_map_init_destroy(gen, lst_init,
					"Map not surrounded by walls");
			if (_in_3_check_characters(tmp->content[x], gen, x, y))
			{
				gen->map.map[x][y].type = (t_chunk_type)tmp->content[x];
				gen->map.map[x][y].status = DOOR_CLOSED;
				gen->map.map[x][y].t0 = to_getime();
				in_3_map_allocate_textures(&gen->textures,
					gen->map.map[x][y].textures, tmp->content[x]);
			}
			else
				in_3_map_init_destroy(gen, lst_init, NULL);
			++x;
		}
		--y;
		tmp = tmp->next;
	}
	// if (!_in_3_check_door(gen))
	// 	end_destroy_exit(gen, EXIT_INIT_3);
}

/**
 * @brief check if the character c is a valid one;
 * 			check for c == DOOR check if door between only 2 walls
 * 				who are oposite
 * 			check for c == 0 if 
 * @param c 
 * @return true if c == 0 1 2 ' '
 * @return false else
 */
static bool	_in_3_check_characters(char c, t_general *gen, int x, int y)
{
	static int	player = false;

	if (!ft_isinset(c, "012 WSEN"))
		return (to_error_msg("Map contains an invalid character"), false);
	if (x == gen->map.width && y == 0) // verifie si le player est la derniere case check;
	{
		if (player == false)
			return (to_error_msg("Map needs a player"), false);
		return (true);
	}
	if (c == 'W' || c == 'E' || c == 'N' || c == 'S')
	{
		if (player == true)
			return (to_error_msg("Map multiple player's porition"), false);
		gen->player.p_co.x = x + 0.5;
		gen->player.p_co.y = y + 0.5;
		player = true;
		if (!_int_3_check_around(c, gen, x, y))
			return (false);
		return (true);
	}
	if (c == WALL || c == FLOOR || c == DOOR || c == NOTHING)
	{
		if (!_int_3_check_around(c, gen, x, y))
			return (false);
		return (true);
	}
	return (false);
}

/**
 * @brief check if necessary if c is not around a NOTHING.
 * 
 * @param gen 
 * @param x 
 * @param y 
 * @return true 
 * @return false 
 */
static bool	_int_3_check_around(char c, t_general *gen, int x, int y)
{
	if (ft_isinset(c, "02WENS"))
	{
		if (x == gen->map.width || y == gen->map.height || x == 0 || y == 0)
			return (to_error_msg("Map not surrounded by walls"), false);
		if (gen->map.map[x - 1][y].type == NOTHING)
			return (to_error_msg("Map not surrounded by walls"), false);
		if (gen->map.map[x][y + 1].type == NOTHING)
			return (to_error_msg("Map not surrounded by walls"), false);
	}
	else if (c == NOTHING)
	{
		if (x != 0 && ft_isinset(gen->map.map[x - 1][y].type, "02WENS"))
			return (to_error_msg("Map not surrounded by walls"), false);
		if (y != gen->map.height
			&& ft_isinset(gen->map.map[x][y + 1].type, "02WENS"))
			return (to_error_msg("Map not surrounded by walls"), false);
	}
	return (true);
}

/**
 * @brief Calloc t_chunk **map;
 * 
 * @param gen 
 * @param lst_init 
 */
static void	_in_3_alloc_tabmap(t_general *gen, t_lists *lst_init)
{
	int	x;

	x = 0;
	gen->map.map = ft_calloc(gen->map.width + 1, sizeof(t_chunk *));
	if (!gen->map.map)
	{
		to_error_msg("Map memory allocation error");
		to_lstfree(&lst_init->lst_param);
		to_lstfree(&lst_init->lst_map);
		end_destroy_exit(gen, EXIT_INIT_3);
	}
	while (x <= gen->map.width)
	{
		gen->map.map[x] = ft_calloc(gen->map.height + 1, sizeof(t_chunk));
		if (!gen->map.map[x])
		{
			to_error_msg("Map memory allocation error");
			to_lstfree(&lst_init->lst_param);
			to_lstfree(&lst_init->lst_map);
			end_destroy_exit(gen, EXIT_INIT_3);
		}
		x++;
	}
}

