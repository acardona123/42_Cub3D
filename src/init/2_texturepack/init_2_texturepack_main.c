/**
 * @brief initializes the texturepack structure by reading the input file,
 *			extracting the textures paths from the linked list generated by
 *			in_1_map_format_check, and generating the textures images
 *			structured as requiered.
 * @param gen 
 * @param lst_init
 * @return EXIT if faillure
 *			on success lst_init->lst_param is freed and set to NULL
 */
void	in_2_init_texture_pack(t_general *gen, t_lists *lst_init)
{
	t_list	*elem;
	char	**line_arg;
	bool	*colors_defined;

	colors_defined = (bool[2]){false, false};
	elem = lst_init->lst_param;
	while (elem)
	{
		line_arg = ft_split(elem->content, ' ');
		if (!line_arg)
			to_error_msg(MSG_BAD_ALLOC);
		if (!line_arg || _in_2_init_texture_or_color(gen->disp.mlx,
				&gen->textures, line_arg, colors_defined) == FAIL)
		{
			ft_tabfree(line_arg);
			in_init_destroy_lists_exit(gen, lst_init, NULL, EXIT_INIT_2);
		}
		ft_tabfree(line_arg);
		elem = elem->next;
	}
	to_lstfree(&lst_init->lst_param);
	if (!in_2_are_all_mandatory_textures_init(&gen->textures, colors_defined))
		in_init_destroy_lists_exit(gen, lst_init, NULL, EXIT_INIT_2);
}

